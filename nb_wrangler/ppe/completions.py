def _gen_fish() -> str:
    """Generate a fish completion script for ``ppe``."""
    lines: list[str] = [
        "# fish completion for ppe",
        "# Generated by nb_wrangler.ppe.completions — do not edit by hand.",
        "",
    ]

    # Top-level group commands (shown when at subcommand position)
    for group in _all_groups():
        desc = _FISH_DESCRIPTIONS.get(group, "")
        lines.append(
            'complete -c ppe -n "__fish_use_subcommand" -a %s -d "%s"' % (group, desc)
        )

    # Sub-commands for each group (shown after the group is seen)
    for group, subcommands in _PPE_COMMAND_TREE.items():
        sub_descs = _FISH_SUBCODESCRIPTIONS.get(group, {})
        for sub in subcommands:
            desc = sub_descs.get(sub, "")
            lines.append(
                'complete -c ppe -n "__fish_seen_subcommand_from %s" -a %s -d "%s"'
                % (group, sub, desc)
            )

    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

_GENERATORS: dict[str, Callable[[], str]] = {
    "bash": _gen_bash,
    "zsh": _gen_zsh,
    "fish": _gen_fish,
}


def generate_completion(shell: str) -> Optional[str]:
    """Return the completion script for *shell*, or ``None`` if unsupported.

    Supported shells: ``bash``, ``zsh``, ``fish``.
    """
    gen = _GENERATORS.get(shell)
    if gen is None:
        return None
    return gen()


def get_supported_shells() -> list[str]:
    """Return the list of supported completion shell names."""
    return list(_GENERATORS.keys())
